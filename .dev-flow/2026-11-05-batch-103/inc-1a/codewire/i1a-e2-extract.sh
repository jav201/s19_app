#!/usr/bin/env bash
# Inc 1a E2: check graph-inc1a.md against the code at e07fb00 with Code-Wire v3.1.0 (tag v3.1.0 = e436a08),
# and list the real callers of every existing node.
# Marks go ONLY into a throwaway copy of s19_app/ under <scratch dir>, never into a worktree.
# Each mark REPLACES the blank line just above its def, so every line number in the reports is e07fb00's.
#   run 1: the baseline subset of the graph (the nodes whose func: starts unchanged / changed / removed)
#          against the marked copy -> expected exit 0 (contracts equal, callers listed).
#   run 2: the whole graph -> expected exit 1, every drift a "graph node without mark" of a NEW node
#          (no code yet; tests are outside the copy).
#   lint : codewire_lint.py on the whole graph (a record: the lines the parser does not read).
# Usage: bash i1a-e2-extract.sh <scratch dir> <repo root at e07fb00> <code-wire clone at v3.1.0>
set -uo pipefail
S="$1"; SRC="$2"; CW="$3"
G="$SRC/.dev-flow/2026-11-05-batch-103/inc-1a/codewire/graph-inc1a.md"
T="$SRC/.dev-flow/2026-11-05-batch-103/inc-1a/codewire/i1a-e2-extract-transcript.txt"
rm -rf "$S"; mkdir -p "$S/repo" "$S/out1" "$S/out2"
cp -r "$SRC/s19_app" "$S/repo/"
find "$S/repo" -name __pycache__ -type d -prune -exec rm -rf {} +
O=s19_app/tui/os_clipboard_input.py
C=s19_app/tui/capped_text_area.py
mark() {  # <file> <def regex> <node name> <indent>
  local f="$S/repo/$1" n prev
  n=$(grep -n -E "$2" "$f" | head -1 | cut -d: -f1)
  if [ -z "$n" ]; then echo "MARK ERROR: no def for $3"; exit 2; fi
  prev=$((n - 1))
  if [ -n "$(sed -n "${prev}p" "$f" | tr -d '[:space:]')" ]; then echo "MARK ERROR: line above $3 is not blank"; exit 2; fi
  sed -i "${prev}s/^.*\$/$4# node: $3/" "$f"
  echo "mark $3 -> $1:$prev (def at $n)"
}
{
  echo "# transcript: i1a-e2-extract.sh, run $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# code-wire: $(git -C "$CW" describe --tags) $(git -C "$CW" rev-parse --short HEAD); repo product tree: $(git -C "$SRC" rev-parse --short HEAD) (git diff e07fb00 -- s19_app: $(git -C "$SRC" diff --stat e07fb00 -- s19_app | wc -l) lines)"
  echo "# python: $(python --version 2>&1)"
  echo
  echo "## marks (each replaces the blank line above its def)"
  for fn in _create_tk_root _destroy_tk_root_singleton _prime_tk_root _read_via_tk _read_via_ctypes \
            _read_via_powershell _write_via_ctypes _write_via_tk _write_via_powershell \
            _bound_clipboard_text read_os_clipboard write_os_clipboard; do
    mark "$O" "^def $fn\(" "$fn" ""
  done
  mark "$O" "^async def _mirror_and_write_os_clipboard\(" "_mirror_and_write_os_clipboard" ""
  for m in __init__ get_or_create get_existing; do mark "$O" "^    def $m\(" "_TkRootSingleton.$m" "    "; done
  for m in action_copy action_cut action_paste; do mark "$O" "^    async def $m\(" "OsClipboardInput.$m" "    "; done
  mark "$C" "^    def _on_paste\(" "CappedTextArea._on_paste" "    "
  for m in action_paste action_copy action_cut; do mark "$C" "^    async def $m\(" "CappedTextArea.$m" "    "; done
  echo
  echo "## line count unchanged by the marks"
  for f in "$O" "$C"; do echo "$f: base $(wc -l < "$SRC/$f") / marked copy $(wc -l < "$S/repo/$f")"; done
  echo
  # the baseline subset: every node block whose func: starts with unchanged / changed / removed
  awk 'BEGIN { RS = ""; ORS = "\n\n"; print "# baseline subset of graph-inc1a.md (generated by i1a-e2-extract.sh)\n" }
       /^## Nodes/ { inn = 1; print "## Nodes"; next }
       /^## /      { inn = 0 }
       inn && /\nfunc: (unchanged|changed|removed)/ { print }' "$G" > "$S/graph-baseline.md"
  echo "## baseline subset: $(grep -c '^func: ' "$S/graph-baseline.md") nodes"
  grep -B5 '^func: ' "$S/graph-baseline.md" | grep -E '^[A-Za-z_][A-Za-z_.]*$' | tr '\n' ' '; echo
  echo
  cd "$S"
  echo "## run 1: baseline subset (expected exit 0)"
  python "$CW/tools/codewire_extract.py" --repo repo --graph graph-baseline.md --path "$O" --path "$C" --out out1
  echo "exit=$?"
  echo
  cat out1/diff-report.md
  echo
  echo "## run 2: whole graph (expected exit 1: only NEW nodes without marks)"
  python "$CW/tools/codewire_extract.py" --repo repo --graph "$G" --path "$O" --path "$C" --out out2
  echo "exit=$?"
  echo
  sed -n '/^## Counts/,/^## Real calls/p' out2/diff-report.md
  sed -n '/^## Graph node without mark/,$p' out2/diff-report.md
  echo
  echo "## lint: whole graph (a record, not a gate)"
  python "$CW/tools/codewire_lint.py" "$G"
  echo "exit=$?"
} 2>&1 | tee "$T"
