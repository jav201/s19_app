#!/usr/bin/env bash
# Inc 11 E2: check graph-inc11.md against the code at e07fb00 with Code-Wire v3.1.0 (tag v3.1.0 = e436a08), and list the
# real callers of every existing node. Marks go ONLY into a throwaway copy (git archive e07fb00 s19_app) under <scratch>,
# never into a worktree. Each mark REPLACES the blank line just above its def, so every line number is e07fb00's.
#   run 1: the baseline subset (the nodes whose func: starts unchanged / changed / removed) -> expected drift only where
#          the graph PROPOSES a new signature (extract_a2l_tags gains `errors`); every other contract equal.
#   run 2: the whole graph -> expected exit 1: run 1's drift plus "graph node without mark" for the NEW nodes.
#   lint : codewire_lint.py on the whole graph (a record, not a gate).
# Copied from Inc 1a's i1a-e2-extract.sh; the node list and the paths differ.
# Usage: bash i11e2-extract.sh <scratch dir> <worktree root> <code-wire clone at v3.1.0>
set -uo pipefail
S="$1"; SRC="$2"; CW="$3"
G="$SRC/.dev-flow/2026-11-05-batch-103/inc-11/codewire/graph-inc11.md"
T="$SRC/.dev-flow/2026-11-05-batch-103/inc-11/codewire/evidence-e2/i11e2-extract-transcript.txt"
rm -rf "$S"; mkdir -p "$S/repo" "$S/out1" "$S/out2"
git -C "$SRC" archive e07fb00 s19_app | tar -x -C "$S/repo"
A=s19_app/tui/a2l.py; P=s19_app/tui/app.py; V=s19_app/validation/rules.py
mark() {  # <file> <def regex> <node name> <indent>
  local f="$S/repo/$1" n prev
  n=$(grep -n -E "$2" "$f" | head -1 | cut -d: -f1)
  if [ -z "$n" ]; then echo "MARK ERROR: no def for $3"; exit 2; fi
  prev=$((n - 1))
  if [ -n "$(sed -n "${prev}p" "$f" | tr -d '[:space:]')" ]; then echo "MARK ERROR: line above $3 is not blank"; exit 2; fi
  sed -i "${prev}s/^.*\$/$4# node: $3/" "$f"
  echo "mark $3 -> $1:$prev (def at $n)"
}
{
  echo "# transcript: i11e2-extract.sh, run $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# code-wire: $(git -C "$CW" describe --tags) $(git -C "$CW" rev-parse --short HEAD); copy: git archive e07fb00 s19_app (worktree HEAD $(git -C "$SRC" rev-parse --short HEAD); git diff e07fb00 -- s19_app: $(git -C "$SRC" diff --stat e07fb00 -- s19_app | wc -l) lines)"
  echo "# python: $(python --version 2>&1)"
  echo
  echo "## marks (each replaces the blank line above its def)"
  for fn in build_section_tree parse_begin_meta _parse_first_field _byte_order_from_section_lines \
            _split_line_respecting_quotes _strip_a2l_comments _flatten_body_tokens parse_measurement_header \
            _characteristic_from_tokens _extended_kind_anchor parse_characteristic_header \
            assemble_characteristic_header _first_header_line _memory_segment_record_words \
            _infer_length_measurement _infer_length_characteristic extract_a2l_tags parse_a2l_file \
            iter_section_lines render_a2l_view; do
    mark "$A" "^def $fn\(" "$fn" ""
  done
  mark "$P" "^    def _compose_screen_a2l\(" "S19TuiApp._compose_screen_a2l" "    "
  mark "$V" "^def validate_a2l_structure\(" "validate_a2l_structure" ""
  echo
  echo "## line count unchanged by the marks"
  for f in "$A" "$P" "$V"; do echo "$f: base $(git -C "$SRC" show e07fb00:"$f" | wc -l) / marked copy $(wc -l < "$S/repo/$f")"; done
  echo
  awk 'BEGIN { RS = ""; ORS = "\n\n"; print "# baseline subset of graph-inc11.md (generated by i11e2-extract.sh)\n" }
       /^## Nodes/ { inn = 1; print "## Nodes"; next }
       /^## /      { inn = 0 }
       inn && /\nfunc: (unchanged|changed|removed)/ { print }' "$G" > "$S/graph-baseline.md"
  echo "## baseline subset: $(grep -c '^func: ' "$S/graph-baseline.md") nodes"
  grep -B5 '^func: ' "$S/graph-baseline.md" | grep -E '^[A-Za-z_][A-Za-z_0-9.]*$' | tr '\n' ' '; echo
  echo
  cd "$S"
  echo "## run 1: baseline subset (expected: drift only on the PROPOSED signature of extract_a2l_tags)"
  python "$CW/tools/codewire_extract.py" --repo repo --graph graph-baseline.md --path "$A" --path "$P" --path "$V" --out out1
  echo "exit=$?"
  echo
  cat out1/diff-report.md
  echo
  echo "## run 2: whole graph (expected exit 1: run 1's drift plus NEW nodes without marks)"
  python "$CW/tools/codewire_extract.py" --repo repo --graph "$G" --path "$A" --path "$P" --path "$V" --out out2
  echo "exit=$?"
  echo
  sed -n '/^## Counts/,/^## Real calls/p' out2/diff-report.md
  sed -n '/^## Graph node without mark/,$p' out2/diff-report.md
  echo
  echo "## lint: whole graph (a record, not a gate)"
  python "$CW/tools/codewire_lint.py" "$G"
  echo "exit=$?"
} 2>&1 | tee "$T"
