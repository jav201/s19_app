#!/usr/bin/env bash
# batch-103 Inc 10 re-map (relevo-8): check the re-mapped graph-inc10.md against the code at the new base with the
# Code-Wire core (marks + extractor), then lint it. Marks go ONLY into a throwaway clone under <scratch>
# (codewire_marks.py writes them there); never into a work tree. Paths printed are relative to <scratch>.
#   run 1: clone at <base>, the baseline subset of the graph (func: unchanged / changed): the real callers of every
#          existing node in its new module -> expected drift only where the graph PROPOSES a new signature
#          (I-10.1 show_save_prompt, I-10.2 SaveBackDecision.__init__)
#   run 2: the whole graph -> run 1's drift plus "graph node without mark" for the 1 NEW node (_set_saveback_format)
#   (no layered run: the earlier graphs of this slice name the pre-split modules, as Inc 8's E2 noted; not a gate)
#   lint : codewire_lint.py on the whole graph (must exit 0 with nothing listed)
# Usage: bash i10-remap-extract.sh <scratch dir> <worktree root> <code-wire clone> <base commit>
set -uo pipefail
S="$1"; SRC="$2"; CW="$3"; BASE="$4"
G="$SRC/.dev-flow/2026-11-05-batch-103/inc-10/codewire/graph-inc10.md"
T="$SRC/.dev-flow/2026-11-05-batch-103/inc-10/evidence-remap/i10-remap-extract-transcript.txt"
rm -rf "$S/clone" "$S/out1" "$S/out2" "$S/graphs"; mkdir -p "$S/graphs"
git clone -q --no-checkout "$SRC" "$S/clone" && git -C "$S/clone" checkout -q "$BASE"
cp "$G" "$S/graphs/graph-inc10.md"
cd "$S"
awk 'BEGIN { RS = ""; ORS = "\n\n"; print "# baseline subset of graph-inc10.md (generated by i10-remap-extract.sh)\n" }
     /^## Nodes/ { inn = 1; print "## Nodes"; next }
     /^## /      { inn = 0 }
     inn && /\nfunc: (unchanged|changed)/ { print }' graphs/graph-inc10.md > graphs/graph-baseline.md
{
  echo "# transcript: i10-remap-extract.sh, run $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# code-wire: $(git -C "$CW" describe --tags) $(git -C "$CW" rev-parse --short HEAD); clone at $(git -C clone rev-parse --short=8 HEAD); worktree HEAD $(git -C "$SRC" rev-parse --short=8 HEAD)"
  echo "# graph sha256 $(sha256sum graphs/graph-inc10.md | cut -d' ' -f1)"
  echo "# python: $(python --version 2>&1)"
  echo
  echo "## baseline subset: $(grep -c '^func: ' graphs/graph-baseline.md) nodes"
  echo
  echo "## run 1: marks + extract, baseline subset (expected: drift only on I-10.1 and I-10.2)"
  python -I -B "$CW/tools/codewire_marks.py" --repo clone --graph graphs/graph-baseline.md --out marks1.json; echo "marks exit=$?"
  python -I -B "$CW/tools/codewire_extract.py" --repo clone --graph graphs/graph-baseline.md --out out1; echo "extract exit=$?"
  cat out1/diff-report.md
  echo
  echo "## run 2: marks + extract, whole graph (expected exit 1: run 1's drift + the NEW node without a mark)"
  python -I -B "$CW/tools/codewire_marks.py" --repo clone --graph graphs/graph-inc10.md --out marks2.json; echo "marks exit=$?"
  python -I -B "$CW/tools/codewire_extract.py" --repo clone --graph graphs/graph-inc10.md --out out2; echo "extract exit=$?"
  cat out2/diff-report.md
  echo
  echo "## lint: whole graph"
  python -I -B "$CW/tools/codewire_lint.py" graphs/graph-inc10.md; echo "lint exit=$?"
  echo
  echo "## clone left as found except marks: $(git -C clone diff --numstat | awk '{a+=$1; d+=$2} END {print a" added, "d" removed lines"}')"
} 2>&1 | tr -d '\r' | tee "$T"
