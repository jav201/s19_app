#!/usr/bin/env bash
# batch-103 Inc 10 E2: check graph-inc10.md against the code with Code-Wire v3.2.0 and list the real callers.
# Marks go ONLY into a throwaway clone under <scratch> (codewire_marks.py writes them and reverts its own earlier
# marks with git checkout); never into a work tree. Every path printed is relative to <scratch>.
#   run 1: clone at <base>, the baseline subset of the graph (func: unchanged / changed)
#          -> expected drift only where the graph PROPOSES a new signature (I-10.1 show_save_prompt, I-10.2
#             SaveBackDecision.__init__)
#   run 2: clone at <base>, the whole graph -> run 1's drift plus "graph node without mark" for the 1 NEW node
#   run 3: layered (not a gate): the earlier graphs that hold nodes of this slice, oldest first, then this graph,
#          limited to the two Python files of the slice -> a list to rule on (E2-rulings.md)
#   lint : codewire_lint.py on the whole graph (must print not read=0)
# Usage: bash i10e2-extract.sh <scratch dir> <worktree root> <code-wire clone> <base commit>
set -uo pipefail
S="$1"; SRC="$2"; CW="$3"; BASE="$4"
D=".dev-flow"
G="$SRC/$D/2026-11-05-batch-103/inc-10/codewire/graph-inc10.md"
T="$SRC/$D/2026-11-05-batch-103/inc-10/codewire/evidence-e2/i10e2-extract-transcript.txt"
EARLIER=(
  "$D/2026-11-01-batch-101/inc-4/codewire/graph-inc4.md"
  "$D/2026-11-01-batch-101/inc-5/codewire/graph-inc5.md"
  "$D/2026-11-01-batch-101/inc-6/codewire/graph-inc6.md"
  "$D/2026-11-05-batch-103/inc-6/codewire/graph-inc6.md"
)
rm -rf "$S/clone" "$S/out1" "$S/out2" "$S/out3" "$S/graphs"; mkdir -p "$S/graphs"
git clone -q --no-checkout "$SRC" "$S/clone" && git -C "$S/clone" checkout -q "$BASE"
cp "$G" "$S/graphs/graph-inc10.md"
i=0; LAYER=()
for g in "${EARLIER[@]}"; do i=$((i+1)); cp "$SRC/$g" "$S/graphs/layer$i-$(basename "$(dirname "$(dirname "$g")")")-$(basename "$g")"; LAYER+=(--graph "graphs/layer$i-$(basename "$(dirname "$(dirname "$g")")")-$(basename "$g")"); done
cd "$S"
awk 'BEGIN { RS = ""; ORS = "\n\n"; print "# baseline subset of graph-inc10.md (generated by i10e2-extract.sh)\n" }
     /^## Nodes/ { inn = 1; print "## Nodes"; next }
     /^## /      { inn = 0 }
     inn && /\nfunc: (unchanged|changed)/ { print }' graphs/graph-inc10.md > graphs/graph-baseline.md
P1=s19_app/tui/screens_directionb.py; P2=s19_app/tui/app.py
{
  echo "# transcript: i10e2-extract.sh, run $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# code-wire: $(git -C "$CW" describe --tags) $(git -C "$CW" rev-parse --short HEAD); clone at $(git -C clone rev-parse --short=8 HEAD); worktree HEAD $(git -C "$SRC" rev-parse --short=8 HEAD)"
  echo "# graph sha256 $(sha256sum graphs/graph-inc10.md | cut -d' ' -f1)"
  echo "# python: $(python --version 2>&1)"
  echo "# layered graphs, oldest first: ${EARLIER[*]} then graph-inc10.md"
  echo
  echo "## baseline subset: $(grep -c '^func: ' graphs/graph-baseline.md) nodes"
  echo
  echo "## run 1: marks + extract, baseline subset (expected: drift only on I-10.1 and I-10.2)"
  python -I "$CW/tools/codewire_marks.py" --repo clone --graph graphs/graph-baseline.md --out marks1.json; echo "marks exit=$?"
  python -I "$CW/tools/codewire_extract.py" --repo clone --graph graphs/graph-baseline.md --out out1; echo "extract exit=$?"
  cat out1/diff-report.md
  echo
  echo "## run 2: marks + extract, whole graph (expected exit 1: run 1's drift + the NEW node without a mark)"
  python -I "$CW/tools/codewire_marks.py" --repo clone --graph graphs/graph-inc10.md --out marks2.json; echo "marks exit=$?"
  python -I "$CW/tools/codewire_extract.py" --repo clone --graph graphs/graph-inc10.md --out out2; echo "extract exit=$?"
  cat out2/diff-report.md
  echo
  echo "## run 3: layered, earlier graphs then this one, the two Python files only (a list to rule on, not a gate)"
  python -I "$CW/tools/codewire_marks.py" --repo clone "${LAYER[@]}" --graph graphs/graph-inc10.md --layered --out marks3.json; echo "marks exit=$?"
  python -I "$CW/tools/codewire_extract.py" --repo clone "${LAYER[@]}" --graph graphs/graph-inc10.md --layered --path "$P1" --path "$P2" --out out3; echo "extract exit=$?"
  cat out3/diff-report.md
  echo
  echo "## lint: whole graph"
  python -I "$CW/tools/codewire_lint.py" graphs/graph-inc10.md; echo "lint exit=$?"
  echo
  echo "## clone left as found except marks: $(git -C clone diff --numstat | awk '{a+=$1; d+=$2} END {print a" added, "d" removed lines"}')"
} 2>&1 | tee "$T"
