#!/usr/bin/env bash
# Inc 12 E2: check graph-inc12.md against the code with Code-Wire v3.1.0 (tag v3.1.0 = e436a08) and list the real
# callers. Marks go ONLY into throwaway copies under <scratch>, never into a worktree; each mark REPLACES the blank line
# just above its def, so every line number is the copy's own (e07fb00's for the base copy).
#   run 1: base copy (git archive e07fb00 s19_app), the baseline subset (func: unchanged / changed) -> expected drift
#          only where the graph PROPOSES a new signature (_build_a2l_table_cells gains `name_width`, I-12.1)
#   run 2: base copy, the whole graph -> run 1's drift plus "graph node without mark" for the 5 NEW nodes
#   run 3: <proto app.py> (the measurement prototype written by i12e2-mkproto.py, variant design, fetched from the
#          runner; sha256 printed) with all 13 nodes marked -> expected exit 0: the graph's contracts are the ones measured
#   lint : codewire_lint.py on the whole graph (a record, not a gate)
# Copied from Inc 11's i11e2-extract.sh; the node list, the nth-match marks and run 3 differ.
# Usage: bash i12e2-extract.sh <scratch dir> <worktree root> <code-wire clone at v3.1.0> <proto app.py>
set -uo pipefail
S="$1"; SRC="$2"; CW="$3"; PROTO="$4"
G="$SRC/.dev-flow/2026-11-05-batch-103/inc-12/codewire/graph-inc12.md"
T="$SRC/.dev-flow/2026-11-05-batch-103/inc-12/codewire/evidence-e2/i12e2-extract-transcript.txt"
rm -rf "$S/base" "$S/protorepo" "$S/out1" "$S/out2" "$S/out3"; mkdir -p "$S/base" "$S/protorepo/s19_app/tui" "$S/out1" "$S/out2" "$S/out3"
git -C "$SRC" archive e07fb00 s19_app | tar -x -C "$S/base"
cp "$PROTO" "$S/protorepo/s19_app/tui/app.py"
P=s19_app/tui/app.py
mark() {  # <repo> <def regex> <node name> <indent> <nth match>
  local f="$1/$P" n prev
  n=$(grep -n -E "$2" "$f" | sed -n "${5}p" | cut -d: -f1)
  if [ -z "$n" ]; then echo "MARK ERROR: no def for $3"; exit 2; fi
  prev=$((n - 1))
  if [ -n "$(sed -n "${prev}p" "$f" | tr -d '[:space:]')" ]; then echo "MARK ERROR: line above $3 is not blank"; exit 2; fi
  sed -i "${prev}s/^.*\$/$4# node: $3/" "$f"
  echo "mark $3 -> $P:$prev (def at $n)"
}
base_marks() {  # <repo> <nth on_resize>
  mark "$1" "^    def _compose_screen_a2l\(" "S19TuiApp._compose_screen_a2l" "    " 1
  mark "$1" "^    def _setup_datatable_columns\(" "S19TuiApp._setup_datatable_columns" "    " 1
  mark "$1" "^    def update_a2l_tags_view\(" "S19TuiApp.update_a2l_tags_view" "    " 1
  mark "$1" "^    def _build_a2l_table_cells\(" "S19TuiApp._build_a2l_table_cells" "    " 1
  mark "$1" "^    def on_resize\(" "S19TuiApp.on_resize" "    " "$2"
  mark "$1" "^    def action_show_screen\(" "S19TuiApp.action_show_screen" "    " 1
  mark "$1" "^    def on_data_table_row_highlighted\(" "S19TuiApp.on_data_table_row_highlighted" "    " 1
  mark "$1" "^def _a2l_detail_card_text\(" "_a2l_detail_card_text" "" 1
}
{
  echo "# transcript: i12e2-extract.sh, run $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# code-wire: $(git -C "$CW" describe --tags) $(git -C "$CW" rev-parse --short HEAD); base copy: git archive e07fb00 s19_app (worktree HEAD $(git -C "$SRC" rev-parse --short HEAD); git diff e07fb00 -- s19_app: $(git -C "$SRC" diff --stat e07fb00 -- s19_app | wc -l) lines)"
  echo "# proto app.py: sha256 $(sha256sum "$PROTO" | cut -d' ' -f1) ($(git -C "$SRC" show e07fb00:$P | diff - "$PROTO" | grep -c '^[<>]') lines differ from e07fb00)"
  echo "# python: $(python --version 2>&1)"
  echo
  echo "## marks, base copy (each replaces the blank line above its def)"
  base_marks "$S/base" 1
  echo
  echo "## marks, proto copy"
  base_marks "$S/protorepo" 2
  mark "$S/protorepo" "^def _shorten_tag_name\(" "_shorten_tag_name" "" 1
  mark "$S/protorepo" "^    def _a2l_tag_name_width\(" "S19TuiApp._a2l_tag_name_width" "    " 1
  mark "$S/protorepo" "^    def _fit_a2l_tag_cells\(" "S19TuiApp._fit_a2l_tag_cells" "    " 1
  mark "$S/protorepo" "^    def on_resize\(" "A2LTagTable.on_resize" "    " 1
  mark "$S/protorepo" "^    def on_a2l_tag_table_measured\(" "S19TuiApp.on_a2l_tag_table_measured" "    " 1
  echo
  echo "## line count unchanged by the marks"
  echo "$P: base $(git -C "$SRC" show e07fb00:$P | wc -l) / marked base copy $(wc -l < "$S/base/$P") / proto $(wc -l < "$PROTO") / marked proto $(wc -l < "$S/protorepo/$P")"
  echo
  awk 'BEGIN { RS = ""; ORS = "\n\n"; print "# baseline subset of graph-inc12.md (generated by i12e2-extract.sh)\n" }
       /^## Nodes/ { inn = 1; print "## Nodes"; next }
       /^## /      { inn = 0 }
       inn && /\nfunc: (unchanged|changed|removed)/ { print }' "$G" > "$S/graph-baseline.md"
  echo "## baseline subset: $(grep -c '^func: ' "$S/graph-baseline.md") nodes"
  grep -B5 '^func: ' "$S/graph-baseline.md" | grep -E '^[A-Za-z_][A-Za-z_0-9.]*$' | tr '\n' ' '; echo
  echo
  cd "$S"
  echo "## run 1: base copy, baseline subset (expected: drift only on the PROPOSED input name_width of _build_a2l_table_cells)"
  python "$CW/tools/codewire_extract.py" --repo base --graph graph-baseline.md --path "$P" --out out1
  echo "exit=$?"
  echo
  cat out1/diff-report.md
  echo
  echo "## run 2: base copy, whole graph (expected exit 1: run 1's drift plus the 5 NEW nodes without marks)"
  python "$CW/tools/codewire_extract.py" --repo base --graph "$G" --path "$P" --out out2
  echo "exit=$?"
  echo
  sed -n '/^## Counts/,/^## Real calls/p' out2/diff-report.md
  sed -n '/^## Graph node without mark/,/^## [^G]/p' out2/diff-report.md
  echo
  echo "## run 3: proto copy, whole graph, 13 marks (expected exit 0)"
  python "$CW/tools/codewire_extract.py" --repo protorepo --graph "$G" --path "$P" --out out3
  echo "exit=$?"
  echo
  cat out3/diff-report.md
  echo
  echo "## lint: whole graph (a record, not a gate)"
  python "$CW/tools/codewire_lint.py" "$G"
  echo "exit=$?"
} 2>&1 | tee "$T"
