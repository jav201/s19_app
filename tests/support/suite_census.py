def timing_arms(tests_root) -> dict:
    """Map ``"file::test"`` to the line of its first ordering assert whose
    operand is a wall-clock interval, or that is or contains a
    ``timing_bound`` / ``report_margin`` call — reached through nested defs
    and called same-module functions, transitively."""
    arms = {}
    for root, path, rel in _test_files(tests_root):
        mod = _parse_module(root, path, rel)
        for test_fn in _iter_test_functions(mod):
            unit = _Unit(mod, test_fn)
            line = _first_arm_assert(test_fn, unit)
            if line is None:
                for rmod, rfn, env in _reached_functions(mod, test_fn, unit):
                    runit = _Unit(rmod, rfn, envs=(env,))
                    line = _first_arm_assert(rfn, runit)
                    if line is not None:
                        break
            if line is not None:
                arms[f"{mod.rel}::{test_fn.name}"] = line
    return arms


def _first_arm_assert(fn, unit: _Unit):
    for assert_node in _asserts_in(fn, include_nested=True):
        if _assert_is_arm(assert_node, unit):
            return assert_node.lineno
    return None


def _assert_is_arm(assert_node: ast.Assert, unit: _Unit) -> bool:
    for node in _walk(assert_node):
        if isinstance(node, ast.Call) and _is_margin_call(node):
            return True
        if isinstance(node, ast.Compare):
            for operand in [node.left, *node.comparators]:
                if unit.classify(operand) == INTERVAL:
                    return True
    return False


def _upper_bound_sides(compare: ast.Compare, unit: _Unit) -> list:
    """Bound-side expressions of the comparison's upper-bound forms whose
    interval side is an interval of the census rule."""
    ops = compare.ops
    sides = []
    if len(ops) == 1:
        if isinstance(ops[0], (ast.Lt, ast.LtE)):
            if unit.classify(compare.left) == INTERVAL:
                sides.append(compare.comparators[0])
        elif isinstance(ops[0], ast.Gt):
            if unit.classify(compare.comparators[0]) == INTERVAL:
                sides.append(compare.left)
    elif len(ops) == 2 and all(
        isinstance(op, (ast.Lt, ast.LtE)) for op in ops
    ):
        if unit.classify(compare.comparators[0]) == INTERVAL:
            sides.append(compare.comparators[1])
    return sides


def unreported_upper_bounds(tests_root, arms) -> list:
    """``"file:line"`` sites whose upper timing bound is not a
    ``report_margin(...)`` call, over the arms and the tests-local
    functions they reach."""
    sites = set()
    by_file: dict = {}
    for nodeid in arms:
        file_part, _, test_name = nodeid.partition("::")
        by_file.setdefault(file_part, set()).add(test_name)
    for root, path, rel in _test_files(tests_root):
        mod = _parse_module(root, path, rel)
        tests_here = by_file.get(mod.rel)
        if not tests_here:
            continue
        for test_fn in _iter_test_functions(mod):
            if test_fn.name not in tests_here:
                continue
            unit = _Unit(mod, test_fn)
            units = [(mod, test_fn, unit)]
            units += [
                (rmod, rfn, _Unit(rmod, rfn, envs=(env,)))
                for rmod, rfn, env in _reached_functions(mod, test_fn, unit)
            ]
            for umod, ufn, uunit in units:
                for assert_node in _asserts_in(ufn, include_nested=True):
                    for node in _walk(assert_node):
                        if not isinstance(node, ast.Compare):
                            continue
                        for side in _upper_bound_sides(node, uunit):
                            if not _is_report_margin_call(side):
                                sites.add(f"{umod.rel}:{node.lineno}")
    return sorted(sites)


