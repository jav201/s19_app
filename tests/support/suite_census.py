def _range_loop_pause_count(fn) -> int:
    count = 0
    for node in ast.walk(fn):
        if isinstance(node, ast.For) and isinstance(node.iter, ast.Call):
            if _callee_name(node.iter.func) == "range":
                for sub in _walk(node):
                    if (
                        isinstance(sub, ast.Await)
                        and isinstance(sub.value, ast.Call)
                        and isinstance(sub.value.func, ast.Attribute)
                        and sub.value.func.attr == "pause"
                    ):
                        count += 1
                        break
    return count


def _wait_until_failure_kinds(fn, source: str) -> tuple:
    """The failure argument of each ``wait_until`` call in the body, as its
    source text (a constant string, an f-string, or a lambda whose body is
    an f-string)."""
    kinds = []
    calls = []
    for node in ast.walk(fn):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if isinstance(node, ast.Call) and _callee_name(node.func) == "wait_until":
            calls.append(node)
    for node in sorted(calls, key=lambda n: (n.lineno, n.col_offset)):
        keywords = {k.arg: k.value for k in node.keywords}
        failure = keywords.get("failure")
        if failure is None and len(node.args) >= 3:
            failure = node.args[2]
        segment = (
            ast.get_source_segment(source, failure)
            if failure is not None
            else None
        )
        kinds.append(segment if segment is not None else "other")
    return tuple(kinds)


def shared_wait_bodies(tests_root) -> dict:
    """Per shared wait helper ("<file path>::<function>"): the number of
    ``for ... in range(...)`` loops whose body awaits ``pilot.pause`` and
    the failure argument of each ``wait_until`` call in the body (as source
    text)."""
    root = Path(tests_root)
    shapes = {}
    for dotted, name in _SHARED_WAITS:
        module = _load_module(root, dotted)
        if module is None or name not in module.functions:
            shapes[f"{dotted.replace('.', '/')}.py::{name}"] = None
            continue
        fn = module.functions[name]
        shapes[f"{module.rel}::{name}"] = (
            _range_loop_pause_count(fn),
            _wait_until_failure_kinds(fn, module.source),
        )
    return shapes
