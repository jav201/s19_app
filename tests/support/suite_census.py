#: Attributes of the ``time`` module that count as wall-clock reads. A plain
#: ``time.time()`` difference (file mtimes) is deliberately NOT a clock:
#: intervals over mtimes carry no performance bound.
_CLOCK_ATTRS = frozenset(
    {
        "perf_counter",
        "perf_counter_ns",
        "monotonic",
        "monotonic_ns",
        "process_time",
        "process_time_ns",
    }
)

#: Calls whose presence in an ordering assert marks a timing arm on its own
#: (form (d) of the timing-arm definition).
_MARGIN_FUNCS = frozenset({"timing_bound", "report_margin"})

#: Callee-name fragments that mark a wait for the newest-line census.
_WAIT_FRAGMENTS = ("wait", "settle", "until", "poll")

UNKNOWN = "unknown"
INTERVAL = "interval"
STAMP = "stamp"


def _walk(node, prune=(ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
    """Yield ``node`` and everything below it in breadth-first order, never
    descending into pruned node types (so a lambda or a nested def's
    internals do not leak into the enclosing assertion's operand scan)."""
    stack = [node]
    while stack:
        current = stack.pop(0)
        if isinstance(current, prune):
            continue
        yield current
        stack.extend(ast.iter_child_nodes(current))


def _nested_fns(fn) -> dict:
    """Nested function definitions directly inside ``fn``'s body."""
    return {
        node.name: node
        for node in getattr(fn, "body", [])
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }


def _all_nested_fns(fn) -> dict:
    """Every nested function at any depth below ``fn``'s body."""
    out = {}
    for node in ast.walk(fn):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node is not fn:
            out[node.name] = node
    return out


class _Module:
    """Parsed test module with its import tables."""

    def __init__(self, path: Path, rel: str, tests_root: Path):
        self.path = path
        self.rel = rel
        self.tests_root = tests_root
        self.source = path.read_text(encoding="utf-8")
        self.tree = ast.parse(self.source, filename=rel)
        self.functions = {
            node.name: node
            for node in self.tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
        }
        #: alias -> dotted module path ("import a.b as x" / "from a import b")
        self.module_aliases = {}
        #: local name -> (dotted module path, original name)
        self.imported_names = {}
        for node in self.tree.body:
            self._collect_import(node)

    def _collect_import(self, node) -> None:
        if isinstance(node, ast.Import):
            for alias in node.names:
                self.module_aliases[alias.asname or alias.name.split(".")[0]] = (
                    alias.name
                )
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                module = "tests" + ("." + node.module if node.module else "")
            else:
                module = node.module
            for alias in node.names:
                if alias.name == "*":
                    continue
                self.imported_names[alias.asname or alias.name] = (module, alias.name)

    def clock_names(self, local_body=()) -> frozenset:
        """Resolved names of the ``time`` module: module-level imports (not
        descending into function or class bodies) plus every import inside
        the given function body."""
        names = set()
        for stmt in self.tree.body:
            if isinstance(
                stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
            ):
                continue
            for node in ast.walk(stmt):
                self._collect_clock_import(node, names)
        for stmt in local_body:
            for node in ast.walk(stmt):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    continue
                self._collect_clock_import(node, names)
        return frozenset(names)

    @staticmethod
    def _collect_clock_import(node, names) -> None:
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == "time":
                    names.add(alias.asname or "time")
        elif isinstance(node, ast.ImportFrom):
            if node.module == "time" and not node.level:
                for alias in node.names:
                    names.add(alias.asname or alias.name)


_module_cache: dict = {}
_file_module_cache: dict = {}


def _parse_module(tests_root: Path, path: Path, rel: str):
    """Parse one test file, cached by absolute path."""
    key = str(path)
    if key not in _file_module_cache:
        _file_module_cache[key] = _Module(path, rel, tests_root)
    return _file_module_cache[key]


def _package_tests_root() -> Path:
    """The tests package the census itself ships in: planted copies scanned
    from a bare directory still refer to the real package's support modules
    (``from tests.b97_probes import last_status``), which resolve here."""
    return Path(__file__).resolve().parent.parent


def _load_module(tests_root: Path, dotted: str):
    """Parse a module of the tests package by dotted path, or None when it
    is not part of the scanned tree (product code, stdlib, missing file).
    A module missing under ``tests_root`` falls back to the tests package
    the census ships in, so planted copies keep their support imports."""
    if dotted == "tests":
        rel = ""
    elif dotted.startswith("tests."):
        rel = dotted[len("tests."):]
    else:
        return None
    key = (str(tests_root), dotted)
    if key in _module_cache:
        return _module_cache[key]
    module = None
    if rel:
        for base in (Path(tests_root), _package_tests_root()):
            candidate = base / (rel.replace(".", "/") + ".py")
            if candidate.is_file():
                module = _Module(candidate, f"tests/{rel.replace('.', '/')}.py", tests_root)
                break
    _module_cache[key] = module
    return module


def _resolve_function(mod: _Module, node, local_fns):
    """Resolve a callee expression to a (module, FunctionDef) pair, by alias
    and name inside ``mod``'s scope only, or None."""
    if isinstance(node, ast.Name):
        if node.id in local_fns:
            return mod, local_fns[node.id]
        if node.id in mod.functions:
            return mod, mod.functions[node.id]
        if node.id in mod.imported_names:
            dotted, name = mod.imported_names[node.id]
            target = _load_module(mod.tests_root, dotted)
            if target is not None and name in target.functions:
                return target, target.functions[name]
            submodule = _load_module(mod.tests_root, f"{dotted}.{name}")
            if submodule is not None:
                return None
        return None
    if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
        base = node.value.id
        if base in mod.module_aliases:
            target = _load_module(mod.tests_root, mod.module_aliases[base])
            if target is not None and node.attr in target.functions:
                return target, target.functions[node.attr]
        if base in local_fns:
            return mod, local_fns[base]
        if base in mod.functions:
            return mod, mod.functions[base]
        if base in mod.imported_names:
            dotted, name = mod.imported_names[base]
            submodule = _load_module(mod.tests_root, f"{dotted}.{name}")
            if submodule is not None and node.attr in submodule.functions:
                return submodule, submodule.functions[node.attr]
    return None


def _is_clock_call(node, clock_names) -> bool:
    """True when ``node`` is a call of a resolved clock name's attribute."""
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and isinstance(node.func.value, ast.Name)
        and node.func.value.id in clock_names
        and node.func.attr in _CLOCK_ATTRS
    )


def _param_names(fn_node) -> list:
    """Positional parameter names, pos-only first."""
    args = getattr(fn_node, "args", None)
    if args is None:
        return []
    return [p.arg for p in getattr(args, "posonlyargs", [])] + [
        p.arg for p in args.args
    ]


def _callee_name(func) -> str:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        return func.attr
    return ""


def _is_margin_call(node) -> bool:
    if not isinstance(node, ast.Call):
        return False
    if isinstance(node.func, ast.Name):
        return node.func.id in _MARGIN_FUNCS
    if isinstance(node.func, ast.Attribute):
        return node.func.attr in _MARGIN_FUNCS
    return False


def _is_report_margin_call(node) -> bool:
    return _is_margin_call(node) and (
        (isinstance(node.func, ast.Name) and node.func.id == "report_margin")
        or (
            isinstance(node.func, ast.Attribute)
            and node.func.attr == "report_margin"
        )
    )


class _Unit:
    """One function analysed as a taint unit: its own body plus every nested
    definition, so a wrapper's ``stamps.append(time.perf_counter())`` marks
    the enclosing list. ``envs`` is the parameter-taint chain: the params
    this unit was called with, then each enclosing unit's params (a nested
    def closes over the enclosing function's parameters)."""

    def __init__(self, mod: _Module, fn, envs=()):
        self.mod = mod
        self.fn = fn
        self.envs = tuple(envs)
        self.local_fns = _all_nested_fns(fn)
        self.clock_names = mod.clock_names(getattr(fn, "body", ()))
        self.stamps = set()
        self.intervals = set()
        self.interval_lists = set()
        self.stamp_lists = set()
        #: name -> set of dict keys holding an interval
        self.dict_keys = {}
        #: name -> classification profile bound to it
        self.profiles = {}
        for _ in range(3):  # small fixpoint: appends feed subscript reads
            if not self._scan_pass():
                break

    # -- body scan ---------------------------------------------------------

    def _scan_pass(self) -> bool:
        before = self._measure()
        for node in ast.walk(self.fn):
            if isinstance(node, ast.Assign):
                self._scan_assign(node)
            elif isinstance(node, ast.AugAssign):
                self._scan_aug_assign(node)
            elif isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
                self._scan_append(node.value)
        return self._measure() != before

    def _measure(self):
        return (
            len(self.stamps),
            len(self.intervals),
            len(self.interval_lists),
            len(self.stamp_lists),
            sum(len(v) for v in self.dict_keys.values()),
            len(self.profiles),
        )

    def _scan_assign(self, node: ast.Assign) -> None:
        kind = self.classify(node.value)
        for target in node.targets:
            self._bind(target, kind)

    def _scan_aug_assign(self, node: ast.AugAssign) -> None:
        kind = self.classify(node.value)
        if isinstance(node.target, ast.Name) and kind in (INTERVAL, STAMP):
            (self.intervals if kind == INTERVAL else self.stamps).add(node.target.id)

    def _bind(self, target, kind) -> None:
        if isinstance(target, ast.Name):
            if kind == INTERVAL:
                self.intervals.add(target.id)
            elif kind == STAMP:
                self.stamps.add(target.id)
            elif isinstance(kind, tuple):
                self.profiles[target.id] = kind
                if kind[0] == "dict":
                    self.dict_keys.setdefault(target.id, set()).update(kind[1])
        elif isinstance(target, ast.Tuple):
            items = kind[1] if isinstance(kind, tuple) and kind[0] == "tuple" else []
            for index, elt in enumerate(target.elts):
                item = items[index] if index < len(items) else UNKNOWN
                self._bind(elt, item)
        elif isinstance(target, ast.Subscript) and isinstance(target.value, ast.Name):
            key = target.slice
            if (
                kind == INTERVAL
                and isinstance(key, ast.Constant)
                and isinstance(key.value, (str, int))
            ):
                self.dict_keys.setdefault(target.value.id, set()).add(key.value)
        elif isinstance(target, ast.Attribute):
            name = self._attr_key(target)
            if name and kind == INTERVAL:
                self.intervals.add(name)
            elif name and kind == STAMP:
                self.stamps.add(name)

    def _scan_append(self, call: ast.Call) -> None:
        if not (
            isinstance(call.func, ast.Attribute)
            and call.func.attr == "append"
            and isinstance(call.func.value, ast.Name)
            and call.args
        ):
            return
        kind = self.classify(call.args[0])
        if kind == INTERVAL:
            self.interval_lists.add(call.func.value.id)
        elif kind == STAMP:
            self.stamp_lists.add(call.func.value.id)

    def _attr_key(self, node: ast.Attribute):
        parts = []
        current = node
        while isinstance(current, ast.Attribute):
            parts.append(current.attr)
            current = current.value
        if isinstance(current, ast.Name):
            parts.append(current.id)
            return ".".join(reversed(parts))
        return None

    def _env_lookup(self, name: str):
        for env in self.envs:
            if name in env:
                return env[name]
        return None

    # -- expression classification -----------------------------------------

    def classify(self, node):
        """Classify an expression: UNKNOWN / INTERVAL / STAMP, a
        ('tuple', [...]) or ('dict', {key: kind}) profile, or a
        ('fn', module, FunctionDef) function reference."""
        if isinstance(node, ast.Name):
            if node.id in self.intervals:
                return INTERVAL
            if node.id in self.stamps:
                return STAMP
            if node.id in self.profiles:
                return self.profiles[node.id]
            if node.id in self.dict_keys:
                return ("dict", {key: INTERVAL for key in self.dict_keys[node.id]})
            if node.id in self.local_fns:
                return ("fn", self.mod, self.local_fns[node.id])
            if node.id in self.mod.functions:
                return ("fn", self.mod, self.mod.functions[node.id])
            env = self._env_lookup(node.id)
            if env is not None:
                return env
            return UNKNOWN
        if isinstance(node, ast.Attribute):
            key = self._attr_key(node)
            if key in self.intervals:
                return INTERVAL
            if key in self.stamps:
                return STAMP
            return UNKNOWN
        if isinstance(node, ast.Subscript):
            if isinstance(node.value, ast.Name):
                name = node.value.id
                if name in self.interval_lists:
                    return INTERVAL
                if name in self.stamp_lists:
                    return STAMP
                if (
                    isinstance(node.slice, ast.Constant)
                    and isinstance(node.slice.value, (str, int))
                    and node.slice.value in self.dict_keys.get(name, ())
                ):
                    return INTERVAL
            container = self.classify(node.value)
            if isinstance(container, tuple) and container[0] in ("tuple", "dict"):
                index = node.slice
                if not isinstance(index, ast.Constant):
                    return UNKNOWN
                if container[0] == "tuple" and isinstance(index.value, int):
                    if 0 <= index.value < len(container[1]):
                        return container[1][index.value]
                if container[0] == "dict":
                    return container[1].get(index.value, UNKNOWN)
            return UNKNOWN
        if isinstance(node, ast.Call):
            if _is_clock_call(node, self.clock_names):
                return STAMP
            resolved = _resolve_function(self.mod, node.func, self.local_fns)
            if resolved is not None:
                arg_env = self._arg_env(resolved[1], node)
                return _return_profile(
                    resolved[0], resolved[1], (arg_env,) + self.envs
                )
            callee_name = _callee_name(node.func)
            env = self._env_lookup(callee_name)
            if isinstance(env, tuple) and env and env[0] == "fn":
                return _deref(env, self.envs)
            # A delegating call (asyncio.run, a support runner, ...): follow
            # a function passed as an argument, e.g. run_app(base, _s).
            for arg in list(node.args) + [k.value for k in node.keywords]:
                target = arg.value if isinstance(arg, ast.Await) else arg
                fn_ref = None
                call_node = None
                if isinstance(target, ast.Name):
                    kind = self.classify(target)
                    if isinstance(kind, tuple) and kind and kind[0] == "fn":
                        fn_ref = kind
                elif isinstance(target, ast.Call):
                    inner = _resolve_function(self.mod, target.func, self.local_fns)
                    if inner is not None:
                        fn_ref = ("fn", inner[0], inner[1])
                        call_node = target
                if fn_ref is not None:
                    arg_env = self._arg_env(fn_ref[2], call_node) if call_node else {}
                    return _deref(fn_ref, (arg_env,) + self.envs)
            return UNKNOWN
        if isinstance(node, ast.Await):
            return self.classify(node.value)
        if isinstance(node, ast.BinOp):
            left = self.classify(node.left)
            right = self.classify(node.right)
            if isinstance(node.op, ast.Sub):
                if left in (INTERVAL, STAMP) or right in (INTERVAL, STAMP):
                    return INTERVAL
                return UNKNOWN
            if isinstance(node.op, ast.Add) and left == INTERVAL and right == INTERVAL:
                return INTERVAL
            return UNKNOWN
        if isinstance(node, ast.IfExp):
            body = self.classify(node.body)
            orelse = self.classify(node.orelse)
            if INTERVAL in (body, orelse):
                return INTERVAL
            if body == STAMP and orelse == STAMP:
                return STAMP
            return UNKNOWN
        if isinstance(node, ast.Tuple):
            return ("tuple", [self.classify(elt) for elt in node.elts])
        if isinstance(node, ast.Dict):
            entries = {}
            for key, value in zip(node.keys, node.values):
                if isinstance(key, ast.Constant) and isinstance(
                    key.value, (str, int)
                ):
                    kind = self.classify(value)
                    if kind == INTERVAL:
                        entries[key.value] = kind
            return ("dict", entries)
        return UNKNOWN

    def _arg_env(self, fn_node, call) -> dict:
        """Map the callee's parameters to the call-site argument taints."""
        env = {}
        positional = [a for a in call.args if not isinstance(a, ast.Starred)]
        params = _param_names(fn_node)
        for index, arg in enumerate(positional):
            if index < len(params):
                env[params[index]] = self.classify(arg)
        for keyword in call.keywords:
            if keyword.arg and keyword.arg in params:
                env[keyword.arg] = self.classify(keyword.value)
        return env


_profile_cache: dict = {}
_profile_stack: list = []


def _envs_key(envs) -> str:
    return repr(envs)


def _deref(kind, outer_envs=()):
    """Resolve a ('fn', module, FunctionDef) reference to its return
    profile."""
    if not (isinstance(kind, tuple) and kind and kind[0] == "fn"):
        return kind
    return _return_profile(kind[1], kind[2], ((),) + tuple(outer_envs))


def _return_profile(mod: _Module, fn_node, envs=()):
    """Taint profile of what ``fn_node`` returns: UNKNOWN / INTERVAL / STAMP,
    ('tuple', [...]) or ('dict', {key: kind}). Returns of nested defs are
    excluded; parameters close over the enclosing envs."""
    key = (
        str(mod.tests_root),
        mod.rel,
        getattr(fn_node, "name", ""),
        getattr(fn_node, "lineno", -1),
        _envs_key(envs),
    )
    if key in _profile_cache:
        return _profile_cache[key]
    if id(fn_node) in _profile_stack:
        return UNKNOWN
    _profile_stack.append(id(fn_node))
    try:
        unit = _Unit(mod, fn_node, envs=envs)
        results = []
        for stmt in fn_node.body:
            candidates = [stmt] if isinstance(stmt, ast.Return) else []
            candidates += [
                node
                for node in _walk(stmt)
                if isinstance(node, ast.Return) and node.value is not None
            ]
            for node in candidates:
                if node.value is not None:
                    results.append(_deref(unit.classify(node.value), unit.envs))
        profile = _merge(results)
        _profile_cache[key] = profile
        return profile
    finally:
        _profile_stack.pop()


def _merge(results: list):
    """Merge alternative classifications (union, optimistic on tuples)."""
    results = [r for r in results if r != UNKNOWN]
    if not results:
        return UNKNOWN
    if len(results) == 1:
        return results[0]
    if any(r == INTERVAL for r in results):
        return INTERVAL
    if all(r == STAMP for r in results):
        return STAMP
    if all(isinstance(r, tuple) and r[0] == "tuple" for r in results):
        width = max(len(r[1]) for r in results)
        column = []
        for index in range(width):
            column.append(
                _merge(
                    [
                        r[1][index]
                        for r in results
                        if index < len(r[1]) and r[1][index] != UNKNOWN
                    ]
                )
            )
        return ("tuple", column)
    if all(isinstance(r, tuple) and r[0] == "dict" for r in results):
        merged = {}
        for r in results:
            merged.update(r[1])
        return ("dict", merged)
    return UNKNOWN


def _test_files(tests_root):
    root = Path(tests_root)
    for path in sorted(root.rglob("test_*.py")):
        yield root, path, path.relative_to(root.parent).as_posix()


def _iter_test_functions(mod: _Module):
    """Top-level test_* functions and test_* methods of Test* classes."""
    for node in mod.tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and (
            node.name.startswith("test_")
        ):
            yield node
        elif isinstance(node, ast.ClassDef) and node.name.startswith("Test"):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)) and (
                    item.name.startswith("test_")
                ):
                    yield item


def _asserts_in(fn, include_nested: bool) -> list:
    """Assert nodes of a function in line order, optionally including the
    bodies of its nested definitions."""
    if include_nested:
        out = [n for n in ast.walk(fn) if isinstance(n, ast.Assert)]
    else:
        out = [
            n
            for stmt in fn.body
            for n in ([stmt] if isinstance(stmt, ast.Assert) else [])
            + [x for x in _walk(stmt) if isinstance(x, ast.Assert)]
        ]
    out.sort(key=lambda a: a.lineno)
    return out


def _reached_functions(mod: _Module, fn, unit: _Unit):
    """(module, FunctionDef, param-env) triples for the tests-local
    functions called from ``fn`` — its own nested defs excluded (they are
    part of the unit), callees included — transitively, with param taints
    unioned across call sites."""
    own_nested = {id(node) for node in unit.local_fns.values()}
    found: dict = {}

    def record(resolved_mod, target, caller_unit, call):
        actuals = {}
        positional = [a for a in call.args if not isinstance(a, ast.Starred)]
        params = _param_names(target)
        for index, arg in enumerate(positional):
            if index < len(params):
                actuals[params[index]] = caller_unit.classify(arg)
        for keyword in call.keywords:
            if keyword.arg in params:
                actuals[keyword.arg] = caller_unit.classify(keyword.value)
        key = id(target)
        if key not in found:
            found[key] = [resolved_mod, target, actuals]
        else:
            existing = found[key][2]
            for name, kind in actuals.items():
                if name not in existing:
                    existing[name] = kind

    def calls_of(node):
        return [n for n in ast.walk(node) if isinstance(n, ast.Call)]

    for node in calls_of(fn):
        resolved = _resolve_function(mod, node.func, unit.local_fns)
        if resolved is not None and id(resolved[1]) not in own_nested:
            record(resolved[0], resolved[1], unit, node)
    seen = set(found)
    queue = [tuple(entry) for entry in found.values()]
    while queue:
        rmod, rfn, _env = queue.pop(0)
        runit = _Unit(rmod, rfn, envs=(_env,))
        for node in calls_of(rfn):
            resolved = _resolve_function(rmod, node.func, runit.local_fns)
            if (
                resolved is None
                or id(resolved[1]) in seen
                or id(resolved[1]) in own_nested
            ):
                continue
            seen.add(id(resolved[1]))
            record(resolved[0], resolved[1], runit, node)
            entry = found[id(resolved[1])]
            queue.append((entry[0], entry[1], entry[2]))
    return [(entry[0], entry[1], entry[2]) for entry in found.values()]


