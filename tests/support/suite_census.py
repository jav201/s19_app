"""Pure-AST census of the test tree (batch-101 Inc 2, test hygiene).

Every predicate here parses test sources with ``ast`` only; the scanned code
is never imported or executed. Imports are resolved by name and alias inside
each module's own scope (module level plus function level for clock imports);
nothing is resolved by a bare name across the tree.

The census answers four questions used by the suite-hygiene guard:

- ``timing_arms`` — which tests assert a wall-clock interval or a
  ``timing_bound`` / ``report_margin`` bound (a *timing arm*);
- ``unreported_upper_bounds`` — which upper timing bounds are not yet a
  ``report_margin(...)`` call;
- ``newest_line_waits`` — which waits poll the newest painted log line
  instead of collecting the lines painted since a mark;
- ``shared_wait_bodies`` — the shapes of the seven shared wait helpers.
"""
