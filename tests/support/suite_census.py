def _is_newest_line_reader(fn) -> bool:
    holds_line4 = any(
        isinstance(node, ast.Constant) and node.value == "#log_line_4"
        for node in ast.walk(fn)
    )
    returns_log_tail = any(
        isinstance(node, ast.Return)
        and node.value is not None
        and _reads_log_lines_tail(node.value)
        for stmt in fn.body
        for node in ([stmt] if isinstance(stmt, ast.Return) else [])
        + [n for n in _walk(stmt) if isinstance(n, ast.Return)]
    )
    return holds_line4 or returns_log_tail


def _is_neg_one(node) -> bool:
    """True for the ``-1`` literal: Constant(-1) or UnaryOp(USub, 1)."""
    if isinstance(node, ast.Constant):
        return node.value == -1
    return (
        isinstance(node, ast.UnaryOp)
        and isinstance(node.op, ast.USub)
        and isinstance(node.operand, ast.Constant)
        and node.operand.value == 1
    )


def _reads_log_lines_tail(node) -> bool:
    for sub in ast.walk(node):
        if (
            isinstance(sub, ast.Subscript)
            and isinstance(sub.value, ast.Attribute)
            and sub.value.attr == "log_lines"
            and _is_neg_one(sub.slice)
        ):
            return True
    return False


def _is_all_line_reader(fn) -> bool:
    for node in ast.walk(fn):
        if isinstance(node, ast.JoinedStr):
            parts = [v for v in node.values if isinstance(v, ast.Constant)]
            if parts and isinstance(parts[0].value, str) and parts[0].value.startswith(
                "#log_line_"
            ):
                return True
        if (
            isinstance(node, ast.Return)
            and node.value is not None
            and _returns_every_log_line(node.value)
        ):
            return True
    return False


def _returns_every_log_line(node) -> bool:
    text = ast.unparse(node)
    return "log_lines" in text and ("list(" in text or " for " in text)


def _module_readers(mod: _Module):
    """(newest-line readers, all-line readers) visible in one module: its
    own functions plus names imported from a module of the tests package."""
    newest = {}
    all_lines = {}
    candidates = dict(mod.functions)
    for name, (dotted, original) in mod.imported_names.items():
        target = _load_module(mod.tests_root, dotted)
        if target is not None and original in target.functions:
            candidates[name] = target.functions[original]
        else:
            submodule = _load_module(mod.tests_root, f"{dotted}.{original}")
            if submodule is not None:
                for attr, fn in submodule.functions.items():
                    candidates.setdefault(f"{name}.{attr}", fn)
    for name, fn in candidates.items():
        if _is_newest_line_reader(fn):
            newest[name] = fn
        if _is_all_line_reader(fn):
            all_lines[name] = fn
    return newest, all_lines


def newest_line_waits(tests_root) -> dict:
    """Per file, the number of wait-named calls with a lambda argument that
    reads only the newest painted log line. Files with 0 are omitted."""
    counts = {}
    for root, path, rel in _test_files(tests_root):
        mod = _parse_module(root, path, rel)
        newest, all_lines = _module_readers(mod)
        newest_ids = set(map(id, newest.values()))
        all_ids = set(map(id, all_lines.values()))
        total = 0
        for node in ast.walk(mod.tree):
            if not isinstance(node, ast.Call):
                continue
            name = _callee_name(node.func).lower()
            if not any(fragment in name for fragment in _WAIT_FRAGMENTS):
                continue
            lambdas = [a for a in node.args if isinstance(a, ast.Lambda)]
            lambdas += [
                k.value for k in node.keywords if isinstance(k.value, ast.Lambda)
            ]
            for lam in lambdas:
                if _lambda_reads_newest_ids(lam, newest_ids, all_ids, mod):
                    total += 1
        if total:
            counts[mod.rel] = total
    return counts


def _lambda_reads_newest_ids(lam, newest_ids: set, all_ids: set, mod: _Module) -> bool:
    for node in ast.walk(lam.body):
        if isinstance(node, ast.Constant) and node.value == "#log_line_4":
            return True
        if _reads_log_lines_tail(node):
            return True
        call = None
        if isinstance(node, ast.Call):
            call = node
        if (
            isinstance(node, ast.Subscript)
            and _is_neg_one(node.slice)
            and isinstance(node.value, ast.Call)
        ):
            call = node.value
        if call is not None:
            resolved = _resolve_function(mod, call.func, {})
            if resolved is not None and (
                id(resolved[1]) in newest_ids or id(resolved[1]) in all_ids
            ):
                return True
    return False


