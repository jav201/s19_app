"""
Computed-address census — how s19_app addresses its widgets, measured by AST.

This module answers one question and refuses to let its answer be copied: **which
call sites address a widget by a selector the reader cannot resolve by grep?**
That is the sizing input for the `C-54` Information Flow Contract, whose `address`
and `consumers` fields only mean something if the set of address forms is known.

Why it is a command and not a table in a document: three separate censuses of this
same surface have now disagreed, and every one of them was accurate the day it was
written. A grep census (2026-08-13) reported 1586 sites with 53 computed ones "all
of one shape"; an AST pass refuted all three figures; and a third pass refuted the
second's totals in turn. The pattern is the one `tools/id_registry.py` states for
its own domain — *"an unstated grep pattern is an unstated definition"* — so this
module states its definitions as code and prints the numbers on demand.

The three definitions that decide every figure below, and each is a correction of a
measurement that went wrong before it:

1. :data:`SELECTOR_RE` — a ``#`` or ``.`` must be followed **immediately** by an
   identifier character or an interpolation. A criterion of merely *"starts with #
   or ."* sweeps in markdown headings (``f"## Variant: {n}"``), prose ellipsis
   (``f"... {n} more ranges"``) and hex colours, and inflates the count by 2.5x.

2. **Format specs are not strings.** ``f"{value:#x}"`` holds a nested ``JoinedStr``
   in the AST — the ``:#x`` spec itself — which reads as an f-string of shape
   ``#x``. Twelve of these exist in the tree and not one is a selector.
   :func:`format_spec_nodes` marks them for exclusion.

3. :data:`ADDRESS_PARAMS` is **derived from Textual, never written**. Textual resolves
   a selector through many doors, and ``pilot.click(f"#{widget_id}")`` is as much a
   computed address as ``query_one``. Written by hand, this set held a name that is not
   a Textual API and missed 16 that are — **and the census printed the same numbers
   either way**, which is why no reading could have caught it.
   :func:`derive_address_params` asks Textual itself, in two composing passes:
   annotation shape finds the query family, then taint seeded from those reaches the
   plain-``str`` methods no annotation reveals. Measured: seeding taint from the raw
   sinks alone reaches 1 of 6; seeding from the annotation pass reaches 6 of 6, plus
   23 per-id APIs on ``Tabs``/``TabbedContent``/``ContentSwitcher`` that nobody watched.

4. **Parameters, not arguments.** Not every argument of an address call is an address:
   ``mount(*widgets, before="#foo")`` takes widgets positionally and the selector by
   keyword only. Counting all arguments reported ``*widgets`` as an unresolvable
   address. :data:`ADDRESS_PARAMS` and :data:`FIRST_POSITIONAL_SELECTOR` narrow it
   to the parameter that actually carries a selector — both derived, not listed. This defect was found by the
   `AT-B83-08` invariant the moment ``mount`` entered the set — not by review.

Example::

    python tools/address_census.py            # census of the repo it lives in
    python tools/address_census.py --json     # machine-readable, for a guard
"""

